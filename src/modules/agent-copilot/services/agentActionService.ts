/**
 * Autonomous CRM Agents & Copilot Module
 * Agent Action Execution Service
 * Handles human-in-the-loop and autopilot action fulfillment
 */

import { AgentInsight } from '../types';
import { agentAuditService } from './agentAuditService';
import { mockStore } from '../../../data/mockStore';
import type { Quote } from '../../../types/quote';
import type { Expense } from '../../../services/expenseService';

export interface ActionExecutionResult {
  success: boolean;
  message: string;
  data?: any;
  error?: string;
}

class AgentActionService {
  /**
   * Dispatches an overdue payment reminder email generated by the Collections Agent.
   */
  public async dispatchPaymentReminder(
    insight: AgentInsight,
    draftData: {
      to: string;
      subject: string;
      body: string;
    }
  ): Promise<ActionExecutionResult> {
    try {
      // 1. Record activity in CRM timeline
      mockStore.addTimelineEvent({
        sourceType: 'AGENT_COLLECTIONS',
        title: `Payment Reminder Dispatched (${insight.metadata?.daysOverdue || 'N/A'}d Overdue)`,
        description: `Collections Agent dispatched reminder to ${draftData.to}: "${draftData.subject}"`,
        actorName: 'Collections & Cash Flow Chaser Agent',
        badgeText: 'Collections Sent',
        badgeVariant: 'green',
      });

      // 2. Record in Agent Audit Log
      agentAuditService.recordFromInsight(
        insight,
        'APPLIED',
        `Dispatched payment reminder email to ${draftData.to}`,
        'CRM Billing Specialist'
      );

      return {
        success: true,
        message: `Payment reminder successfully queued and dispatched to ${draftData.to}`,
        data: {
          recipient: draftData.to,
          subject: draftData.subject,
          dispatchedAt: new Date().toISOString(),
        },
      };
    } catch (err: any) {
      return {
        success: false,
        message: 'Failed to dispatch payment reminder',
        error: err.message,
      };
    }
  }

  /**
   * Applies margin discount correction suggested by the Deal Health Agent.
   */
  public async applyQuoteDiscount(
    insight: AgentInsight,
    newDiscountPercent: number
  ): Promise<ActionExecutionResult> {
    try {
      const quoteId = insight.entityId;
      const quote = mockStore.getById<Quote>('quotes', quoteId);
      if (!quote) {
        throw new Error(`Quote ${quoteId} not found`);
      }

      const subtotal = quote.subtotal || quote.total_amount || 0;
      const newDiscountAmount = (subtotal * newDiscountPercent) / 100;
      const newTotal = subtotal - newDiscountAmount + (quote.tax_amount || 0);

      mockStore.update<Quote>('quotes', quoteId, {
        discount_amount: newDiscountAmount,
        total_amount: newTotal,
      });

      mockStore.addTimelineEvent({
        sourceType: 'AGENT_DEAL_HEALTH',
        title: `Quote Discount Adjusted to ${newDiscountPercent}%`,
        description: `Deal Health Agent recommendation applied to Quote ${quote.quote_number}. Subtotal: €${subtotal.toLocaleString()}, New Discount: €${newDiscountAmount.toLocaleString()}`,
        actorName: 'Deal Health & CPQ Estimator Agent',
        badgeText: 'Discount Adjusted',
        badgeVariant: 'blue',
      });

      agentAuditService.recordFromInsight(
        insight,
        'APPLIED',
        `Discount adjusted from ${insight.metadata?.originalDiscountPercent || 'original'}% to ${newDiscountPercent}%`,
        'Sales Operations'
      );

      return {
        success: true,
        message: `Quote ${quote.quote_number} discount updated to ${newDiscountPercent}% successfully`,
        data: {
          newDiscountAmount,
          newTotal,
        },
      };
    } catch (err: any) {
      return {
        success: false,
        message: 'Failed to update quote discount',
        error: err.message,
      };
    }
  }

  /**
   * Extends the valid_until date for an expiring quote.
   */
  public async extendQuoteValidity(
    insight: AgentInsight,
    additionalDays: number = 14
  ): Promise<ActionExecutionResult> {
    try {
      const quoteId = insight.entityId;
      const quote = mockStore.getById<Quote>('quotes', quoteId);
      if (!quote) throw new Error(`Quote ${quoteId} not found`);

      const currentExpiry = quote.valid_until ? new Date(quote.valid_until) : new Date();
      const newExpiry = new Date(currentExpiry.getTime() + additionalDays * 24 * 60 * 60 * 1000);
      const newExpiryIso = newExpiry.toISOString().split('T')[0];

      mockStore.update<Quote>('quotes', quoteId, {
        valid_until: newExpiryIso,
      });

      mockStore.addTimelineEvent({
        sourceType: 'AGENT_DEAL_HEALTH',
        title: `Quote Validity Extended by ${additionalDays} Days`,
        description: `Deal Health Agent extended expiry date for Quote ${quote.quote_number} to ${newExpiryIso}`,
        actorName: 'Deal Health & CPQ Estimator Agent',
        badgeText: 'Quote Extended',
        badgeVariant: 'yellow',
      });

      agentAuditService.recordFromInsight(
        insight,
        'APPLIED',
        `Quote extended by ${additionalDays} days to ${newExpiryIso}`,
        'Account Manager'
      );

      return {
        success: true,
        message: `Quote ${quote.quote_number} validity extended to ${newExpiryIso}`,
        data: { newExpiryIso },
      };
    } catch (err: any) {
      return {
        success: false,
        message: 'Failed to extend quote validity',
        error: err.message,
      };
    }
  }

  /**
   * Generates a draft renewal quote for an expiring contract.
   */
  public async generateRenewalQuote(insight: AgentInsight): Promise<ActionExecutionResult> {
    try {
      const contractId = insight.entityId;
      const contract = mockStore.getById<any>('contracts', contractId);
      const randomSuffix = Math.floor(1000 + Math.random() * 9000);
      const newQuoteNumber = `QTE-RNW-2026-${randomSuffix}`;

      const renewalAmount = contract?.contract_value || contract?.total_amount || 15000;
      const currency = contract?.currency_code || 'EUR';

      const newQuote: Partial<Quote> = {
        quote_number: newQuoteNumber,
        customer_id: contract?.customer_id || contract?.party_b_name,
        company_settings_id: contract?.company_settings_id,
        status: 'draft',
        quote_date: new Date().toISOString().split('T')[0],
        valid_until: new Date(Date.now() + 30 * 24 * 60 * 60 * 1000).toISOString().split('T')[0],
        currency_code: currency,
        subtotal: renewalAmount,
        discount_amount: 0,
        tax_amount: renewalAmount * 0.2, // 20% standard VAT
        total_amount: renewalAmount * 1.2,
        notes: `Automated contract renewal quote synthesized by Contract Compliance Agent for ${contract?.contract_title || 'Master Agreement'} (${contract?.contract_number || ''}).`,
        customer: {
          company_name: contract?.party_b_name || 'Enterprise Customer',
        } as any,
      };

      const inserted = mockStore.insert<Quote>('quotes', newQuote as Quote);

      mockStore.addTimelineEvent({
        sourceType: 'AGENT_COMPLIANCE',
        title: `Draft Renewal Quote Created (${newQuoteNumber})`,
        description: `Contract Compliance Agent auto-generated renewal quote for ${contract?.contract_title || 'Contract'} valued at ${currency} ${renewalAmount.toLocaleString()}`,
        actorName: 'Contract Compliance & Renewal Agent',
        badgeText: 'Renewal Drafted',
        badgeVariant: 'purple',
      });

      agentAuditService.recordFromInsight(
        insight,
        'APPLIED',
        `Generated renewal quote ${newQuoteNumber} linked to contract ${contract?.contract_number || contractId}`,
        'Compliance & Legal Agent'
      );

      return {
        success: true,
        message: `Draft renewal quote ${newQuoteNumber} generated successfully`,
        data: inserted,
      };
    } catch (err: any) {
      return {
        success: false,
        message: 'Failed to generate renewal quote',
        error: err.message,
      };
    }
  }

  /**
   * Flags duplicate expense or marks for controller review.
   */
  public async flagExpenseAnomaly(
    insight: AgentInsight,
    action: 'mark_duplicate_rejected' | 'approve_exception',
    notes?: string
  ): Promise<ActionExecutionResult> {
    try {
      const expenseId = insight.entityId;
      const expense = mockStore.getById<Expense>('expenses', expenseId);
      if (!expense) throw new Error(`Expense ${expenseId} not found`);

      if (action === 'mark_duplicate_rejected') {
        mockStore.update<Expense>('expenses', expenseId, {
          payment_status: 'rejected' as any,
          description: `${expense.description || ''} [FLAGGED DUPLICATE BY AGENT: ${notes || 'Rejected'}]`,
        });

        mockStore.addTimelineEvent({
          sourceType: 'AGENT_FINANCE',
          title: `Duplicate Expense Rejected: ${expense.expense_number}`,
          description: `Financial Anomaly Auditor flagged and rejected duplicate expense of ${expense.amount} (${expense.vendor_name})`,
          actorName: 'Financial Anomaly & Expense Auditor',
          badgeText: 'Duplicate Flagged',
          badgeVariant: 'red',
        });

        agentAuditService.recordFromInsight(
          insight,
          'APPLIED',
          `Rejected expense ${expense.expense_number} as duplicate. ${notes || ''}`,
          'Financial Controller'
        );

        return {
          success: true,
          message: `Expense #${expense.expense_number} marked as duplicate and rejected`,
        };
      } else {
        // approve exception
        mockStore.addTimelineEvent({
          sourceType: 'AGENT_FINANCE',
          title: `Expense Exception Approved: ${expense.expense_number}`,
          description: `Controller reviewed and cleared financial anomaly warning for ${expense.vendor_name}`,
          actorName: 'Financial Controller',
          badgeText: 'Anomaly Cleared',
          badgeVariant: 'green',
        });

        agentAuditService.recordFromInsight(
          insight,
          'APPROVED',
          `Cleared anomaly flag as legitimate expense. ${notes || ''}`,
          'Financial Controller'
        );

        return {
          success: true,
          message: `Expense #${expense.expense_number} verified and anomaly flag cleared`,
        };
      }
    } catch (err: any) {
      return {
        success: false,
        message: 'Failed to resolve expense anomaly',
        error: err.message,
      };
    }
  }

  /**
   * Dismiss an insight with an optional human reason.
   */
  public dismissInsight(insight: AgentInsight, reason?: string): void {
    agentAuditService.recordFromInsight(
      insight,
      'DISMISSED',
      reason || 'Dismissed by CRM operator',
      'CRM Operator'
    );
  }
}

export const agentActionService = new AgentActionService();
export default agentActionService;

